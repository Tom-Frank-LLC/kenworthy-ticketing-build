#!/usr/bin/env node
/**
 * Writes android/app/version.properties with a fresh versionCode.
 *
 * Google Play rejects an upload whose versionCode is not higher than every
 * one it has seen for the app, and a hand-bumped number gets forgotten. So the
 * number is derived, the same way as the iOS build number
 * (scripts/stamp-ios-build.mjs): whole minutes since 2026-01-01 00:00 UTC. It
 * only goes up, needs no state, and stays under Play's 2,100,000,000 ceiling
 * for about four thousand years.
 *
 * versionName (1.0.0) is in android/app/build.gradle — bump it there, by hand,
 * per store release, alongside the iOS MARKETING_VERSION.
 *
 * Refuses to run if build.gradle holds a literal versionCode: that would win,
 * and this file would be written and silently ignored.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const GRADLE = 'android/app/build.gradle';
const codes = readFileSync(GRADLE, 'utf8').split('\n').filter((l) => /^\s*versionCode\b/.test(l));
if (codes.length !== 1 || !codes[0].includes("versionProps.getProperty('versionCode'")) {
  console.error(`✖ stamp-android-build: ${GRADLE} must take versionCode from version.properties; found:\n${codes.join('\n') || '(none)'}`);
  process.exit(1);
}

const code = Math.floor((Date.now() - Date.UTC(2026, 0, 1)) / 60000);
writeFileSync('android/app/version.properties', `# GENERATED by scripts/stamp-android-build.mjs. Do not edit; do not commit.\nversionCode=${code}\n`);
console.log(`✔ stamp-android-build: versionCode ${code}`);
