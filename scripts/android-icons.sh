#!/bin/sh
# Regenerates the Android launcher icon and launch-screen mark from
# public/icons/icon.svg, the same mark the PWA and the iOS app use (see
# scripts/ios-icons.sh). macOS only (sips). Run from the repo root.
#
# Android 8+ draws an adaptive icon: a background layer (the page's #0f0f0f,
# values/ic_launcher_background.xml) under a foreground layer that the launcher
# masks to its own shape — circle, squircle, teardrop. Only the middle 66 of the
# foreground's 108 units are guaranteed visible (a circle of radius 33), so
# the mark is drawn 48 units wide, centred: its corners then sit 32 units out.
# The foreground is a vector made from the SVG's own path data, so it is sharp
# at every density, and the launch screen reuses it (Android 12+ masks the
# splash icon the same way).
#
# Android 7 (minSdk 24) has no adaptive icons and uses the PNGs in mipmap-*:
# the square icon as is, and a round one drawn on a circle for launchers that
# ask for ic_launcher_round.
set -e
SVG=public/icons/icon.svg
RES=android/app/src/main/res
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# The mark's two paths, in the SVG's 950-unit space after its own
# translate(152,152) scale(0.68). Their painted bounds there are x 202–751,
# y 219–711 (centre 476.5, 465), measured by rasterising icon.svg at 950px.
# Map that box to 48 units wide centred at (54, 54). Re-measure if the SVG changes.
PATHS=$(grep -o ' d="[^"]*"' "$SVG" | sed -E 's/ d="([^"]*)"/\1/')
[ "$(printf '%s\n' "$PATHS" | wc -l | tr -d ' ')" = 2 ] || { echo "expected 2 paths in $SVG" >&2; exit 1; }
FILL=$(grep -o 'fill="#d4a247"' "$SVG" | head -1 | sed -E 's/fill="(.*)"/\1/')
{
  echo '<?xml version="1.0" encoding="utf-8"?>'
  echo '<!-- GENERATED by scripts/android-icons.sh from public/icons/icon.svg. Do not edit. -->'
  echo '<vector xmlns:android="http://schemas.android.com/apk/res/android"'
  echo '    android:width="108dp" android:height="108dp"'
  echo '    android:viewportWidth="108" android:viewportHeight="108">'
  # 48/549 = 0.087432; centre (476.5,465)·0.087432 = (41.66,40.66) → shift (12.34,13.34).
  # The inner translate/scale is the SVG's own group transform.
  echo '  <group android:translateX="12.34" android:translateY="13.34" android:scaleX="0.087432" android:scaleY="0.087432">'
  echo '    <group android:translateX="152" android:translateY="152" android:scaleX="0.68" android:scaleY="0.68">'
  printf '%s\n' "$PATHS" | while read -r d; do
    echo "      <path android:fillColor=\"$FILL\" android:pathData=\"$d\"/>"
  done
  echo '    </group>'
  echo '  </group>'
  echo '</vector>'
} > "$RES/drawable/ic_launcher_foreground.xml"

INNER=$(sed -E 's/.*<rect[^>]*\/>(.*)<\/svg>.*/\1/' "$SVG")
printf '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 950 950"><circle cx="475" cy="475" r="475" fill="#0f0f0f"/>%s</svg>' "$INNER" > "$TMP/round.svg"
for pair in mdpi:48 hdpi:72 xhdpi:96 xxhdpi:144 xxxhdpi:192; do
  dpi=${pair%%:*}; px=${pair##*:}
  mkdir -p "$RES/mipmap-$dpi"
  sips -s format png -z "$px" "$px" "$SVG" --out "$RES/mipmap-$dpi/ic_launcher.png" >/dev/null
  sips -s format png -z "$px" "$px" "$TMP/round.svg" --out "$RES/mipmap-$dpi/ic_launcher_round.png" >/dev/null
done
echo "✔ android-icons: adaptive foreground + legacy mipmaps written"
