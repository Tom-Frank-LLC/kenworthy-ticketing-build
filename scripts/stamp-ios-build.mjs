#!/usr/bin/env node
/**
 * Writes ios/Version.xcconfig with a fresh build number (CURRENT_PROJECT_VERSION).
 *
 * App Store Connect rejects an upload whose build number it has seen before for
 * the same version, and a hand-bumped number gets forgotten. So the number is
 * derived: whole minutes since 2026-01-01 00:00 UTC. It only goes up, needs no
 * state, and two archives a minute apart cannot collide.
 *
 * The marketing version (1.0.0) is MARKETING_VERSION in project.pbxproj —
 * bump it there, by hand, per App Store release.
 *
 * It also writes SQUARE_APPLICATION_ID, which Info.plist hands to Square's
 * Mobile Payments SDK at launch (the Stand, BRIEF-ios-stand-reader.md). It is
 * read off the backend the app's copied bundle actually points at, not a flag,
 * so a staging bundle can only ever talk to Square's sandbox and a production
 * bundle to production. Both ids are public: each environment's ticket-checkout
 * get_config returns its own.
 *
 * Refuses to run if project.pbxproj holds a literal build number: a literal
 * there beats any xcconfig, so this file would be written and silently ignored
 * (Xcode's General → Identity → "Build" field writes one).
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const PBX = 'ios/App/App.xcodeproj/project.pbxproj';
const lines = readFileSync(PBX, 'utf8').split('\n').filter((l) => /CURRENT_PROJECT_VERSION =/.test(l));
const literal = lines.filter((l) => !/= "\$\(inherited\)";/.test(l));
if (lines.length === 0 || literal.length) {
  console.error(`✖ stamp-ios-build: ${PBX} must set CURRENT_PROJECT_VERSION = "$(inherited)"; found:\n${literal.join('\n') || '(none)'}`);
  process.exit(1);
}

const SQUARE_APP = {
  vlmslygnimfbamrtwvyo: 'sq0idp-gimxBVaATLLQetsP7qa_7g', // production
  rpqzrpboyhshdrfdwayk: 'sandbox-sq0idb-pfgKPmMAtOyj0qj4bALh9g', // staging → Square sandbox
};
const assets = 'ios/App/App/public/assets';
const refs = new Set();
if (existsSync(assets)) {
  for (const name of readdirSync(assets)) {
    if (!name.endsWith('.js')) continue;
    for (const m of readFileSync(join(assets, name), 'utf8').matchAll(/https:\/\/([a-z]{20})\.supabase\.co/g)) refs.add(m[1]);
  }
}
if (refs.size !== 1 || !SQUARE_APP[[...refs][0]]) {
  console.error(`✖ stamp-ios-build: the app's bundle points at ${[...refs].join(', ') || 'no backend'}; run \`cap sync ios\` with a production or staging build first.`);
  process.exit(1);
}
const squareApp = SQUARE_APP[[...refs][0]];

const build = Math.floor((Date.now() - Date.UTC(2026, 0, 1)) / 60000);
writeFileSync('ios/Version.xcconfig', `// GENERATED by scripts/stamp-ios-build.mjs. Do not edit; do not commit.\nCURRENT_PROJECT_VERSION = ${build}\nSQUARE_APPLICATION_ID = ${squareApp}\n`);
console.log(`✔ stamp-ios-build: build number ${build}, Square application ${squareApp}`);
